export const DEFAULT_MARKETING_THEME: MarketingThemeId = "fuchsia-flash";
export const STORAGE_KEY = "antrahq-marketing-theme";

export const marketingThemeList = Object.values(marketingThemes);

export function getThemesByCategory(category: MarketingThemeCategory): MarketingTheme[] {
  return marketingThemeList.filter((t) => t.category === category);
}

export function getMarketingTheme(id: string): MarketingTheme {
  if (id in marketingThemes) return marketingThemes[id as MarketingThemeId];
  return marketingThemes[DEFAULT_MARKETING_THEME];
}

export function themeToCssVars(theme: MarketingTheme): Record<string, string> {
  const s = theme.section;
  const g = theme.site;
  return {
    "--mkt-page-bg": g.pageBg,
    "--mkt-header-bg": g.headerBg,
    "--mkt-site-text": g.text,
    "--mkt-site-text-muted": g.textMuted,
    "--mkt-primary": g.primary,
    "--mkt-primary-hover": g.primaryHover,
    "--mkt-primary-soft": g.primarySoft,
    "--mkt-primary-glow": g.primaryGlow,
    "--mkt-site-border": g.border,
    "--mkt-bg": s.background,
    "--mkt-text": s.text,
    "--mkt-text-muted": s.textMuted,
    "--mkt-accent": s.accent,
    "--mkt-accent-soft": s.accentSoft,
    "--mkt-accent-glow": s.accentGlow,
    "--mkt-card-bg": s.cardBg,
    "--mkt-card-border": s.cardBorder,
    "--mkt-node-idle": s.nodeIdle,
    "--mkt-node-active": s.nodeActive,
    "--mkt-edge": s.edge,
    "--mkt-edge-active": s.edgeActive,
    "--mkt-orb-primary": s.orbPrimary,
    "--mkt-orb-secondary": s.orbSecondary,
    "--mkt-grid": s.gridColor,
    "--mkt-badge-bg": s.badgeBg,
    "--mkt-badge-border": s.badgeBorder,
  };
}

export function applyThemeToDocument(theme: MarketingTheme) {
  const root = document.documentElement;
  const vars = themeToCssVars(theme);
  Object.entries(vars).forEach(([key, value]) => root.style.setProperty(key, value));
  root.dataset.marketingTheme = theme.id;
}

